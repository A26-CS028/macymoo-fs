-- 001_init.sql: skema awal macymoo, mengikuti erd_macyourmoo (tim DS)
-- Tipe: id = integer identity, string = TEXT, decimal = NUMERIC(12,2),
-- timestamp = TIMESTAMPTZ.

CREATE TABLE menus (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         TEXT,
  price        NUMERIC(12,2),
  photo_url    TEXT,
  is_available BOOLEAN
);

CREATE TABLE menu_options (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  menu_id     INTEGER NOT NULL REFERENCES menus(id),
  name        TEXT,
  extra_price NUMERIC(12,2)
);

CREATE TABLE orders (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code      TEXT,
  customer_name   TEXT,
  phone           TEXT,
  source          TEXT,
  status          TEXT,
  pay_timing      TEXT,
  pay_status      TEXT,
  discount        NUMERIC(12,2),
  public_token    TEXT,
  invoice_sent_at TIMESTAMPTZ,
  created_at      TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE deliveries (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id        INTEGER NOT NULL REFERENCES orders(id),
  delivery_date   DATE,
  method          TEXT,
  address         TEXT,
  shipping_fee    NUMERIC(12,2),
  delivery_status TEXT
);

CREATE TABLE order_items (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id     INTEGER NOT NULL REFERENCES orders(id),
  menu_id      INTEGER REFERENCES menus(id),   -- kosong untuk item bebas, bundling, bonus
  custom_name  TEXT,
  custom_price NUMERIC(12,2),
  qty          INTEGER,
  unit_price   NUMERIC(12,2),
  note         TEXT
);

CREATE TABLE order_item_options (
  order_item_id  INTEGER NOT NULL REFERENCES order_items(id),
  menu_option_id INTEGER NOT NULL REFERENCES menu_options(id),
  PRIMARY KEY (order_item_id, menu_option_id)
);

CREATE TABLE order_item_labels (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_item_id INTEGER NOT NULL REFERENCES order_items(id),
  label         TEXT   -- hasil MooLabel
);

CREATE TABLE payments (
  id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders(id),
  type     TEXT,
  method   TEXT,
  amount   NUMERIC(12,2),
  paid_at  TIMESTAMPTZ
);

CREATE TABLE invoices (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   INTEGER NOT NULL REFERENCES orders(id),
  invoice_no TEXT,
  revision   INTEGER,
  issued_at  DATE
);

-- UNIQUE(order_id): ERD menandai relasi orders ke reviews sebagai nol atau satu
CREATE TABLE reviews (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id          INTEGER NOT NULL UNIQUE REFERENCES orders(id),
  rating            INTEGER,
  comment           TEXT,
  token             TEXT,
  moderation_status TEXT
);

CREATE TABLE admin_users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT,
  password_hash TEXT,
  role          TEXT
);

-- admin_id boleh kosong: ERD menandai admin_users ke order_events sebagai nol atau satu
CREATE TABLE order_events (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    INTEGER NOT NULL REFERENCES orders(id),
  admin_id    INTEGER REFERENCES admin_users(id),
  event_type  TEXT,
  from_status TEXT,
  to_status   TEXT,
  old_date    DATE,
  new_date    DATE,
  reason      TEXT,
  created_at  TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE closed_dates (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  closed_date DATE,
  reason      TEXT
);

CREATE TABLE settings (
  key   TEXT PRIMARY KEY,
  value TEXT
);

CREATE TABLE chat_logs (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_message TEXT,
  bot_reply    TEXT,
  created_at   TIMESTAMPTZ DEFAULT now()
);
