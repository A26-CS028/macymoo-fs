-- 001_init.sql: skema awal macymoo (16 tabel).
-- Sumber: erd_macyourmoo (tim DS), direvisi sesuai catatan review DS (erd_review_notes.md)
-- dan macymoo_Keputusan_Final.md (KF).
--
-- Aturan penting:
-- * Uang = INTEGER (Rupiah bulat).
-- * Harga disalin saat pesan: order_items.unit_price (harga dasar) dan
--   order_item_options.extra_price (harga tambahan opsi). Mengubah menu tidak mengubah pesanan lama.
-- * Total item = qty * (unit_price + SUM(extra_price opsi item itu)). Dihitung di services/pricing.js.
-- * Ongkir hanya di deliveries.shipping_fee. Tidak ada kolom total di orders maupun invoices.
-- * invoice_no disimpan tanpa akhiran -v2; revisi ada di kolom revision.
--
-- Dijalankan sekali, di database kosong.

CREATE TABLE menus (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         TEXT    NOT NULL,
  price        INTEGER NOT NULL CHECK (price >= 0),
  photo_url    TEXT,
  is_available BOOLEAN NOT NULL DEFAULT true
);

-- option_group tanpa CHECK: daftar kelompok divalidasi di backend (Joi)
-- supaya menu baru dengan kelompok opsi baru tidak terblokir database.
-- Contoh: pedas, keju, ayam, tanpa_makaroni, tanpa_brokoli.
CREATE TABLE menu_options (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  menu_id      INTEGER NOT NULL REFERENCES menus(id),
  option_group TEXT,
  name         TEXT    NOT NULL,
  extra_price  INTEGER NOT NULL DEFAULT 0 CHECK (extra_price >= 0)
);

-- customer_name, phone: boleh kosong karena fitur Anonimkan.
CREATE TABLE orders (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code      TEXT    NOT NULL UNIQUE,
  customer_name   TEXT,
  phone           TEXT,
  source          TEXT    NOT NULL CHECK (source IN ('web_form', 'admin_form')),
  status          TEXT    NOT NULL DEFAULT 'Menunggu Konfirmasi'
                  CHECK (status IN ('Menunggu Konfirmasi', 'Menunggu Pembayaran', 'Diproses', 'Selesai', 'Dibatalkan')),
  pay_timing      TEXT    NOT NULL DEFAULT 'di_muka'   -- KF bagian 4: default bayar di muka
                  CHECK (pay_timing IN ('di_muka', 'setelah_kirim')),
  pay_status      TEXT    NOT NULL DEFAULT 'Belum Bayar'
                  CHECK (pay_status IN ('Belum Bayar', 'DP', 'Lunas', 'Dikembalikan')),
  discount        INTEGER NOT NULL DEFAULT 0 CHECK (discount >= 0),
  public_token    TEXT    NOT NULL UNIQUE,
  invoice_sent_at TIMESTAMPTZ,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX orders_phone_idx ON orders (phone);

CREATE TABLE deliveries (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id        INTEGER NOT NULL REFERENCES orders(id),
  delivery_date   DATE    NOT NULL,
  method          TEXT    NOT NULL CHECK (method IN ('antar_nabila', 'ambil_sendiri')),
  address         TEXT,
  shipping_fee    INTEGER NOT NULL DEFAULT 0 CHECK (shipping_fee >= 0),
  delivery_status TEXT    NOT NULL DEFAULT 'Dijadwalkan'
                  CHECK (delivery_status IN ('Dijadwalkan', 'Terkirim')),
  delivered_at    TIMESTAMPTZ
);

-- Satu item milik satu pengiriman (delivery_id). Backend memastikan
-- delivery_id berasal dari pesanan yang sama dengan order_id.
-- menu_id kosong untuk item bebas, bundling, bonus, dan kolaborasi.
CREATE TABLE order_items (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    INTEGER NOT NULL REFERENCES orders(id),
  delivery_id INTEGER NOT NULL REFERENCES deliveries(id),
  menu_id     INTEGER REFERENCES menus(id),
  item_type   TEXT    NOT NULL DEFAULT 'menu'
              CHECK (item_type IN ('menu', 'item_bebas', 'bundling', 'bonus', 'kolaborasi')),
  custom_name TEXT,
  qty         INTEGER NOT NULL CHECK (qty > 0),
  unit_price  INTEGER NOT NULL CHECK (unit_price >= 0),
  note        TEXT,
  CHECK (menu_id IS NOT NULL OR custom_name IS NOT NULL),
  CHECK (item_type <> 'menu' OR menu_id IS NOT NULL)
);

CREATE TABLE order_item_options (
  order_item_id  INTEGER NOT NULL REFERENCES order_items(id),
  menu_option_id INTEGER NOT NULL REFERENCES menu_options(id),
  extra_price    INTEGER NOT NULL CHECK (extra_price >= 0),   -- tanpa default: backend wajib menyalin harga saat pesan (0 bila gratis)
  PRIMARY KEY (order_item_id, menu_option_id)
);

CREATE TABLE order_item_labels (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_item_id INTEGER NOT NULL REFERENCES order_items(id),
  label         TEXT    NOT NULL,   -- hasil MooLabel
  model_version TEXT,
  UNIQUE (order_item_id, label)
);

-- amount selalu positif; arah ditentukan type.
-- Pembayaran bersih = (dp + pelunasan) - refund.
CREATE TABLE payments (
  id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders(id),
  type     TEXT    NOT NULL CHECK (type IN ('dp', 'pelunasan', 'refund')),
  method   TEXT    NOT NULL CHECK (method IN ('qris', 'transfer', 'tunai')),
  amount   INTEGER NOT NULL CHECK (amount > 0),
  paid_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- issued_at dihitung zona Asia/Jakarta di backend.
CREATE TABLE invoices (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   INTEGER NOT NULL REFERENCES orders(id),
  invoice_no TEXT    NOT NULL,
  revision   INTEGER NOT NULL DEFAULT 1 CHECK (revision >= 1),
  issued_at  DATE    NOT NULL,
  UNIQUE (invoice_no, revision)
);

-- Satu review per pesanan. Baris dibuat saat tautan review dibuat:
-- rating dan comment kosong sampai pelanggan mengirim.
-- Token berlaku sampai token_expires_at dan hangus setelah review terkirim.
CREATE TABLE reviews (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id          INTEGER NOT NULL UNIQUE REFERENCES orders(id),
  rating            INTEGER CHECK (rating BETWEEN 1 AND 5),
  comment           TEXT,
  token             TEXT    NOT NULL UNIQUE,
  token_expires_at  TIMESTAMPTZ NOT NULL,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  moderation_status TEXT    NOT NULL DEFAULT 'pending'
                    CHECK (moderation_status IN ('pending', 'approved', 'rejected'))
);

CREATE TABLE admin_users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL
);

-- event_type: status_change (perpindahan status), reschedule (jadwal ulang satu pengiriman),
--             cancel (pembatalan; from_status dan to_status juga diisi), bill_sent (Kirim Tagihan).
-- Lewat batas bayar tidak dicatat sebagai event: dihitung saat dibaca dari invoice_sent_at.
-- admin_id boleh kosong. delivery_id boleh kosong (dipakai untuk jadwal ulang
-- satu pengiriman pada pesanan multi-pengiriman).
CREATE TABLE order_events (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    INTEGER NOT NULL REFERENCES orders(id),
  delivery_id INTEGER REFERENCES deliveries(id),
  admin_id    INTEGER REFERENCES admin_users(id),
  event_type  TEXT    NOT NULL
              CHECK (event_type IN ('status_change', 'reschedule', 'cancel', 'bill_sent')),
  from_status TEXT
              CHECK (from_status IN ('Menunggu Konfirmasi', 'Menunggu Pembayaran', 'Diproses', 'Selesai', 'Dibatalkan')),
  to_status   TEXT
              CHECK (to_status IN ('Menunggu Konfirmasi', 'Menunggu Pembayaran', 'Diproses', 'Selesai', 'Dibatalkan')),
  old_date    DATE,
  new_date    DATE,
  reason      TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE closed_dates (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  closed_date DATE NOT NULL UNIQUE,
  reason      TEXT
);

CREATE TABLE settings (
  key   TEXT PRIMARY KEY,
  value TEXT
);

CREATE TABLE chat_logs (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_message TEXT NOT NULL,
  bot_reply    TEXT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Rate limit disimpan di database karena serverless (KF bagian 11).
-- key: pembatas dan pengenalnya, mis. 'login:<hash>', 'order:<hash>', 'moobot:<hash>', 'review:<hash>'.
-- Simpan hash alamat IP, bukan IP mentah (data pribadi).
-- Baris lama dihapus oleh backend saat menulis (tanpa cron).
CREATE TABLE rate_limits (
  key          TEXT        NOT NULL,
  window_start TIMESTAMPTZ NOT NULL,
  hits         INTEGER     NOT NULL DEFAULT 1 CHECK (hits > 0),
  PRIMARY KEY (key, window_start)
);
